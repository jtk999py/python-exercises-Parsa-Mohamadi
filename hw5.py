import math
x=int(input('مسافت طی شده را بر حسب کیلومتر وارد کنید :'))
if x<=2:
    print('هزینه سفر شما 20 هزار تومان میباشد.')
else:
    q=((x-2)*5+20)
    print(f'هزینه ی سفر شما{q} هزار تومان میباشد')
    